'use strict';

/**
 * Renders scripts/schema.js into a console setup guide.
 *
 * Catalyst Data Store has no programmatic table creation (the SDK exposes only
 * getAllTables/getTableDetails/table(id), and the CLI has no create command),
 * so the 26 tables must be created by hand in the console. This produces an
 * exact, tickable checklist so nothing is mistyped — column names are matched
 * verbatim by the query builders and the seed script.
 *
 * Run: node scripts/generate-setup-guide.js
 */

const fs = require('fs');
const path = require('path');
const { TABLES, totalColumns } = require('./schema');

const TYPE_HELP = {
  INT: 'Number',
  VARCHAR: 'Text',
  TEXT: 'Text (max length)',
  DATE: 'Date',
  DATETIME: 'DateTime',
  DECIMAL: 'Double',
  BOOLEAN: 'Boolean',
};

const lookup = TABLES.filter(t => t.group === 'lookup');
const txn = TABLES.filter(t => t.group === 'transactional');

function renderTable(t, i) {
  const rows = t.columns.map(c => {
    const type = c.type === 'VARCHAR' ? `Text (${c.len})` : TYPE_HELP[c.type];
    return `| \`${c.name}\` | ${type} | ${c.note || ''} |`;
  }).join('\n');
  return `### ${i}. \`${t.name}\`  *(${t.columns.length} columns)*
${t.purpose}

| Column | Data type | Notes |
|---|---|---|
${rows}
`;
}

let n = 0;
const out = `# Data Store Console Setup Guide

> Generated by \`scripts/generate-setup-guide.js\` — do not edit by hand.

**${TABLES.length} tables · ${totalColumns} columns** to create in
**Catalyst console → Cloud Scale → Data Store → New Table**.

## Before you start

1. **Column names must match exactly** (including case). The seed script and the
   ZCQL query builders look columns up by name — a typo silently breaks that table.
2. **Do not create** \`ROWID\`, \`CREATEDTIME\`, \`MODIFIEDTIME\` or \`CREATORID\` —
   Catalyst adds those itself.
3. Leave **Mandatory** and **Unique** unchecked on every column. The \`*ID\` primary
   keys are ordinary Number columns we populate ourselves; Data Store does not
   enforce foreign keys, so referential integrity is maintained by the seed data.
4. **Booleans**: set the default to \`false\`.
5. Create tables in the order below — it follows dependency order, which is also
   the order the seeder inserts in.

## ⚠️ Name collision

The schema's \`Accused\` table clashes with the **existing \`Accused\` table**
(124 rows: \`name\`, \`fir_count\`, \`is_repeat_offender\`, …). To avoid destroying
working data mid-migration, the new one is named **\`AccusedPerson\`** here.
Everything downstream uses that name. Once the migration is verified you can
delete the old \`Accused\`, \`FIRs\`, \`Alerts\` tables.

---

## Lookup / master tables (${lookup.length})

${lookup.map(t => renderTable(t, ++n)).join('\n')}

---

## Transactional tables (${txn.length})

${txn.map(t => renderTable(t, ++n)).join('\n')}

---

## When you're done

Tell me and I'll run the seeder, which verifies every table exists and reports
row counts per table before inserting anything.
`;

const outPath = path.resolve(__dirname, '..', 'docs', 'DATASTORE-SETUP.md');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out);

console.log(`Wrote ${path.relative(process.cwd(), outPath)}`);
console.log(`  ${TABLES.length} tables, ${totalColumns} columns`);
console.log(`  lookup: ${lookup.length}, transactional: ${txn.length}`);
